    static let gameSceneSwift = """
    //
    //  GameRuntime.swift
    //  {{PROJECT_NAME}}
    //
    //  Game runtime that loads and executes game data
    //  Generated by UntoldEngine Build System
    //

    import Foundation
    import UntoldEngine

    /// Lightweight runtime wrapper that loads bundled game data and starts the engine
    class GameRuntime {

        private var loadedScenes: [Scene] = []
        private var loadedScripts: [USCScript] = []

        init() {
            Logger.log(message: "🎮 {{PROJECT_NAME}} Runtime Initialized")
        }

        /// Load all game data from the bundle
        func loadGameData() {
            Logger.log(message: "📦 Loading game data...")

            // Load scenes
            loadScenes()

            // Load USC scripts
            loadScripts()

            // Initialize scripting system
            initScriptingSystem()

            Logger.log(message: "✅ Game data loaded successfully")
        }

        /// Start the game
        func run() {
            Logger.log(message: "🚀 Starting {{PROJECT_NAME}}...")

            // Initialize the engine with first scene
            if let firstScene = loadedScenes.first {
                initEngine(scene: firstScene)
            } else {
                Logger.log(message: "⚠️ No scenes found, creating default scene")
                initEngine(scene: createDefaultScene())
            }

            // Start the main loop
            startGameLoop()
        }

        // MARK: - Private Helpers

        private func loadScenes() {
            guard let gameDataURL = Bundle.main.url(forResource: "GameData", withExtension: nil) else {
                Logger.log(message: "⚠️ GameData directory not found")
                return
            }

            let scenesURL = gameDataURL.appendingPathComponent("Scenes")

            guard let sceneFiles = try? FileManager.default.contentsOfDirectory(
                at: scenesURL,
                includingPropertiesForKeys: nil
            ) else {
                Logger.log(message: "⚠️ No scenes directory found")
                return
            }

            for sceneFile in sceneFiles where sceneFile.pathExtension == "json" {
                if let scene = loadScene(from: sceneFile) {
                    loadedScenes.append(scene)
                    Logger.log(message: "📄 Loaded scene: \\(scene.name)")
                }
            }
        }

        private func loadScene(from url: URL) -> Scene? {
            guard let data = try? Data(contentsOf: url),
                  let scene = try? JSONDecoder().decode(Scene.self, from: data) else {
                Logger.log(message: "❌ Failed to load scene from \\(url.lastPathComponent)")
                return nil
            }
            return scene
        }

        private func loadScripts() {
            guard let gameDataURL = Bundle.main.url(forResource: "GameData", withExtension: nil) else {
                return
            }

            let scriptsURL = gameDataURL.appendingPathComponent("Scripts")

            guard let scriptFiles = try? FileManager.default.contentsOfDirectory(
                at: scriptsURL,
                includingPropertiesForKeys: nil
            ) else {
                Logger.log(message: "⚠️ No scripts directory found")
                return
            }

            for scriptFile in scriptFiles where scriptFile.pathExtension == "uscript" {
                if let script = loadUSCScript(from: scriptFile) {
                    loadedScripts.append(script)
                    Logger.log(message: "📜 Loaded script: \\(script.name)")
                }
            }
        }

        private func createDefaultScene() -> Scene {
            let scene = createScene(named: "DefaultScene")
            Logger.log(message: "🎬 Created default scene")
            return scene
        }

        private func startGameLoop() {
            // The engine's main loop will take over from here
            Logger.log(message: "🔄 Game loop started")
        }
    }
    """

