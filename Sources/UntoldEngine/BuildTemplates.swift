                // Find the scene file but DON'T load it yet
                findBundledScene()

                // Load USC scripts from GameData/Scripts
                loadBundledScripts()

                // Initialize game systems for play mode
                gameMode = true
                AnimationSystem.shared.isEnabled = true
                USCSystem.shared.startPlayMode() 
